#!/usr/bin/env python
"""WP9: compile the revised manuscript reproducibly and record docs/revision/wp8/manuscript_manifest.json.

latexmk runs with SOURCE_DATE_EPOCH and FORCE_SOURCE_DATE fixed, so the same sources and TeX installation
give a byte-identical PDF in any directory. The Springer Nature template asks for a single .tex file, so the
script also writes main_submission.tex with every \\input inlined and compiles it in a temporary directory to
confirm that it produces the same document. The manifest records the source, bibliography, generated-asset
and PDF hashes, the page count and the TeX engine. Use --check to compile without rewriting the manifest
and report whether the PDF matches the recorded hash (used by the snapshot verification).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
MANUSCRIPT = PROJECT_ROOT.parent / "computers_security_revision"
MANIFEST = PROJECT_ROOT / "docs/revision/wp8/manuscript_manifest.json"
SOURCE_DATE_EPOCH = "1789430400"  # 2026-09-15T00:00:00Z
INTERMEDIATES = (".aux", ".bbl", ".blg", ".fdb_latexmk", ".fls", ".log", ".out", ".abs", ".spl")
INPUT_PATTERN = re.compile(r"\\input\{([^}]+)\}")


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def flatten() -> Path:
    """Inline every \\input into a single submission file (the class forbids \\input in submitted sources)."""

    def inline(match: re.Match) -> str:
        target = MANUSCRIPT / match.group(1)
        if target.suffix != ".tex":
            target = target.with_suffix(".tex")
        # Extra line breaks here become glue inside resizebox/table arguments.
        # Preserve the input bytes instead of surrounding them with annotations.
        return target.read_text()

    text = (MANUSCRIPT / "main.tex").read_text()
    for _ in range(5):
        text, count = INPUT_PATTERN.subn(inline, text)
        if not count:
            break
    header = ("%% Single-file submission source, generated by scripts/revision/wp9_compile_manuscript.py from\n"
              "%% main.tex and the generated assets. Do not edit: edit main.tex and regenerate.\n")
    path = MANUSCRIPT / "main_submission.tex"
    path.write_text(header + text)
    return path


def pdf_content_fingerprint(pdf: Path, output: Path) -> dict:
    """Compare text and rendered content, ignoring PDF metadata and job-name differences."""
    output.mkdir()
    common = ["gs", "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE"]
    subprocess.run(common + ["-sDEVICE=txtwrite", f"-sOutputFile={output / 'text.txt'}", str(pdf)],
                   capture_output=True, text=True, check=True)
    subprocess.run(common + ["-sDEVICE=png16m", "-r144", f"-sOutputFile={output / 'page-%03d.png'}", str(pdf)],
                   capture_output=True, text=True, check=True)
    return {"text_sha256": sha(output / "text.txt"),
            "rendered_page_sha256": [sha(p) for p in sorted(output.glob("page-*.png"))]}


def check_flattened(path: Path, pages: int) -> dict:
    """Compile the single-file source and compare page count, text, and page renders."""

    env = os.environ | {"SOURCE_DATE_EPOCH": SOURCE_DATE_EPOCH, "FORCE_SOURCE_DATE": "1"}
    with tempfile.TemporaryDirectory() as scratch:
        scratch = Path(scratch)
        for name in ("references.bib", "sn-jnl.cls", "sn-basic.bst"):
            if (MANUSCRIPT / name).exists():
                shutil.copy2(MANUSCRIPT / name, scratch / name)
        shutil.copytree(MANUSCRIPT / "generated/figures", scratch / "generated/figures")
        shutil.copy2(path, scratch / "main_submission.tex")
        result = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "main_submission.tex"],
                                cwd=scratch, env=env, capture_output=True, text=True)
        if result.returncode != 0:
            return {"compiles": False, "error": result.stdout[-800:]}
        count = subprocess.run(["gs", "-q", "-dNODISPLAY", "-dNOSAFER", "-c",
                                "(main_submission.pdf) (r) file runpdfbegin pdfpagecount = quit"],
                               cwd=scratch, capture_output=True, text=True, check=True).stdout.strip()
        original = pdf_content_fingerprint(MANUSCRIPT / "main.pdf", scratch / "original_content")
        flattened = pdf_content_fingerprint(scratch / "main_submission.pdf", scratch / "flattened_content")
        renderer = subprocess.run(["gs", "--version"], capture_output=True, text=True, check=True).stdout.strip()
    return {"compiles": True, "pages": int(count), "same_pages_as_main": int(count) == pages,
            "same_text_as_main": original["text_sha256"] == flattened["text_sha256"],
            "same_rendered_pages_as_main": (len(original["rendered_page_sha256"]) == pages
                                            and original["rendered_page_sha256"] == flattened["rendered_page_sha256"]),
            "render_dpi": 144, "ghostscript_version": renderer,
            "main_content": original, "submission_content": flattened}


def compile_pdf() -> dict:
    for suffix in INTERMEDIATES:
        (MANUSCRIPT / f"main{suffix}").unlink(missing_ok=True)
    env = os.environ | {"SOURCE_DATE_EPOCH": SOURCE_DATE_EPOCH, "FORCE_SOURCE_DATE": "1"}
    result = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "main.tex"],
                            cwd=MANUSCRIPT, env=env, capture_output=True, text=True)
    (MANUSCRIPT / "build.log").write_text(result.stdout + result.stderr, encoding="utf-8")
    if result.returncode != 0:
        raise SystemExit(f"latexmk failed ({result.returncode}); see {MANUSCRIPT / 'build.log'}")
    log = (MANUSCRIPT / "main.log").read_text(errors="replace")
    pages = subprocess.run(["gs", "-q", "-dNODISPLAY", "-dNOSAFER", "-c", "(main.pdf) (r) file runpdfbegin pdfpagecount = quit"],
                           cwd=MANUSCRIPT, capture_output=True, text=True, check=True).stdout.strip()
    engine = subprocess.run(["pdflatex", "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    return {
        "main_tex_sha256": sha(MANUSCRIPT / "main.tex"),
        "references_bib_sha256": sha(MANUSCRIPT / "references.bib"),
        "assets_manifest_sha256": sha(PROJECT_ROOT / "docs/revision/wp8/assets_manifest.json"),
        "main_pdf_sha256": sha(MANUSCRIPT / "main.pdf"),
        "pages": int(pages),
        "undefined_references": len(re.findall(r"undefined", log)),
        "overfull_hboxes": len(re.findall(r"Overfull \\hbox", log)),
        "source_date_epoch": SOURCE_DATE_EPOCH,
        "tex_engine": engine,
        "script_sha256": sha(Path(__file__)),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compile and compare with the recorded manifest without rewriting it")
    args = parser.parse_args()
    record = compile_pdf()
    submission = flatten()
    record["submission_tex_sha256"] = sha(submission)
    record["submission_single_file_check"] = check_flattened(submission, record["pages"])
    submission_check = record["submission_single_file_check"]
    required = ("compiles", "same_pages_as_main", "same_text_as_main", "same_rendered_pages_as_main")
    if not all(submission_check.get(key) is True for key in required):
        print(json.dumps({"submission_verification_failed": submission_check}, indent=1))
        return 1
    if args.check:
        recorded = json.loads(MANIFEST.read_text())
        keys = ("main_tex_sha256", "references_bib_sha256", "assets_manifest_sha256", "main_pdf_sha256", "pages", "submission_tex_sha256", "script_sha256", "submission_single_file_check")
        mismatches = {k: (recorded.get(k), record[k]) for k in keys if recorded.get(k) != record[k]}
        print(json.dumps({"matches_manifest": not mismatches, "mismatches": mismatches}, indent=1))
        return 1 if mismatches else 0
    MANIFEST.write_text(json.dumps(record, indent=1) + "\n")
    print(json.dumps(record, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
